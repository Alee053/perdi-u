-- Dedicated demo runtime: DML only, no administrative or schema privileges.
\set ON_ERROR_STOP on

SELECT format('CREATE ROLE perdiu_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L', :'app_password')
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'perdiu_app') \gexec
SELECT format('ALTER ROLE perdiu_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L', :'app_password') \gexec

REVOKE ALL ON DATABASE perdiu_demo_dev FROM PUBLIC;
GRANT CONNECT ON DATABASE perdiu_demo_dev TO perdiu_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO perdiu_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO perdiu_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO perdiu_app;
ALTER DEFAULT PRIVILEGES FOR ROLE perdiu IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO perdiu_app;
ALTER DEFAULT PRIVILEGES FOR ROLE perdiu IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO perdiu_app;
REVOKE ALL ON TABLE schema_migrations FROM perdiu_app;
